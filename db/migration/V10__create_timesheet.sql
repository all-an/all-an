-- Timesheet: one row per person per day, and the constants its rules read.

-- The three computed columns are stored as whole minutes, not decimal hours: 7h20m is exactly 440,
-- and a month of them sums without rounding drift. The server calculates them whenever a row is
-- saved (all_an/timesheet.py), so they are columns a report can read directly.
CREATE TABLE timesheet (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id       BIGINT      NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    work_date     DATE        NOT NULL,

    -- WORK is a day with hours. The others are days that belong in the month but are neutral for
    -- the minimum-hours and on-site rules, so they carry no times.
    day_type      VARCHAR(16) NOT NULL DEFAULT 'WORK',

    start_hour    TIME,
    start_lunch   TIME,
    end_lunch     TIME,
    end_work_hour TIME,

    below_minimum INTEGER     NOT NULL DEFAULT 0,
    above_minimum INTEGER     NOT NULL DEFAULT 0,
    total_worked  INTEGER     NOT NULL DEFAULT 0,

    onsite        BOOLEAN     NOT NULL DEFAULT FALSE,
    notes         TEXT,

    created_at    TIMESTAMP(6) WITH TIME ZONE NOT NULL DEFAULT NOW(),
    updated_at    TIMESTAMP(6) WITH TIME ZONE NOT NULL DEFAULT NOW(),

    CONSTRAINT uq_timesheet_user_date UNIQUE (user_id, work_date),
    CONSTRAINT chk_timesheet_day_type CHECK (day_type IN ('WORK', 'LEAVE', 'HOLIDAY', 'SICK')),
    -- A working day has a start and an end; any other kind of day has no times at all.
    CONSTRAINT chk_timesheet_work_has_times CHECK (
        (day_type = 'WORK' AND start_hour IS NOT NULL AND end_work_hour IS NOT NULL)
        OR (day_type <> 'WORK' AND start_hour IS NULL AND start_lunch IS NULL
            AND end_lunch IS NULL AND end_work_hour IS NULL AND NOT onsite)
    ),
    -- Lunch is optional, but half a lunch is not a lunch.
    CONSTRAINT chk_timesheet_lunch_pair CHECK ((start_lunch IS NULL) = (end_lunch IS NULL)),
    CONSTRAINT chk_timesheet_order CHECK (
        start_hour < end_work_hour
        AND (start_lunch IS NULL OR (start_hour < start_lunch AND start_lunch < end_lunch AND end_lunch < end_work_hour))
    ),
    CONSTRAINT chk_timesheet_minutes CHECK (below_minimum >= 0 AND above_minimum >= 0 AND total_worked >= 0)
);

-- (user_id, work_date) is already indexed by the unique key, which serves the year, month and week
-- reads: they all filter on one user and a range of dates.

-- Constants the timesheet rules read, in the same key/value shape as app_settings, and for the
-- same reason: changing one should not need a deploy.
CREATE TABLE timesheet_constants (
    key        TEXT NOT NULL PRIMARY KEY,
    value      TEXT NOT NULL,
    updated_at TIMESTAMP(6) WITH TIME ZONE NOT NULL DEFAULT NOW()
);

