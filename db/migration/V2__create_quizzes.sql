CREATE TABLE quizzes (
    id                         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    -- NULL means the quiz was seeded by the application itself. Those rows are public and nobody
    -- can edit or delete them through the API, so the starter content cannot be vandalised.
    owner_id                   BIGINT REFERENCES users (id) ON DELETE CASCADE,

    title                      VARCHAR(120) NOT NULL,
    description                TEXT,
    study_field_id             SMALLINT     NOT NULL REFERENCES study_fields (id),
    -- Free text within the field: 'English grammar', 'Mental arithmetic', 'World capitals'.
    subject                    VARCHAR(64)  NOT NULL,

    visibility                 VARCHAR(8)   NOT NULL DEFAULT 'PRIVATE',

    -- What a newly added question inherits. Authoring twenty questions should not mean typing the
    -- same number twenty times.
    default_time_limit_seconds INTEGER      NOT NULL DEFAULT 30,
    -- Whether an attempt draws the questions in the author's order or shuffled.
    shuffle_questions          BOOLEAN      NOT NULL DEFAULT FALSE,

    created_at                 TIMESTAMP(6) WITH TIME ZONE NOT NULL DEFAULT NOW(),
    updated_at                 TIMESTAMP(6) WITH TIME ZONE NOT NULL DEFAULT NOW(),

    CONSTRAINT chk_quizzes_visibility CHECK (visibility IN ('PRIVATE', 'PUBLIC')),
    CONSTRAINT chk_quizzes_default_time_limit CHECK (default_time_limit_seconds BETWEEN 5 AND 600),
    CONSTRAINT chk_quizzes_title_not_blank CHECK (LENGTH(TRIM(title)) > 0),
    CONSTRAINT chk_quizzes_subject_not_blank CHECK (LENGTH(TRIM(subject)) > 0)
);

CREATE INDEX idx_quizzes_owner ON quizzes (owner_id);

-- Partial, because the public pool is the only listing that pages through quizzes it does not
-- already have an owner_id for. Restricting the index to PUBLIC rows keeps it small however many
-- private drafts accumulate.
CREATE INDEX idx_quizzes_public ON quizzes (study_field_id, subject, created_at DESC)
    WHERE visibility = 'PUBLIC';

CREATE TABLE questions (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    quiz_id            BIGINT   NOT NULL REFERENCES quizzes (id) ON DELETE CASCADE,
    position           SMALLINT NOT NULL,

    kind               VARCHAR(16) NOT NULL,
    prompt             TEXT        NOT NULL,
    -- Shown after the answer is submitted, never before. Optional: not every question needs one.
    explanation        TEXT,
    time_limit_seconds INTEGER     NOT NULL,

    CONSTRAINT chk_questions_kind CHECK (kind IN ('MULTIPLE_CHOICE', 'TYPED')),
    CONSTRAINT chk_questions_time_limit CHECK (time_limit_seconds BETWEEN 5 AND 600),
    CONSTRAINT chk_questions_prompt_not_blank CHECK (LENGTH(TRIM(prompt)) > 0),
    -- Positions are unique within a quiz, so "question 3" is never ambiguous.
    CONSTRAINT uq_questions_quiz_position UNIQUE (quiz_id, position)
);

CREATE INDEX idx_questions_quiz ON questions (quiz_id, position);

-- One table serves both question kinds, and the two readings are genuinely different:
--
--   MULTIPLE_CHOICE - the choices shown to the learner. is_correct marks the answer, and it must
--                     never be sent to the browser before an answer is submitted.
--   TYPED           - the accepted spellings of the answer. Never shown at all; every row is
--                     is_correct = TRUE. Several rows means several ways of writing the same
--                     answer, which is the norm rather than the exception.
CREATE TABLE question_options (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    question_id BIGINT       NOT NULL REFERENCES questions (id) ON DELETE CASCADE,
    position    SMALLINT     NOT NULL,
    body        VARCHAR(300) NOT NULL,
    is_correct  BOOLEAN      NOT NULL,

    CONSTRAINT chk_question_options_body_not_blank CHECK (LENGTH(TRIM(body)) > 0),
    CONSTRAINT uq_question_options_question_position UNIQUE (question_id, position)
);

CREATE INDEX idx_question_options_question ON question_options (question_id, position);
