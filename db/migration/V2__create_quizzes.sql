-- Quizzes and the questions inside them.
--
-- The quiz, not the question, is the unit: title, classification and visibility live here, and a
-- question belongs to exactly one quiz. You browse, publish, take and score quizzes - never a
-- loose question.

-- The top level of a two-level classification. Curated and seeded here rather than user-writable,
-- because open-ended top-level categories degenerate within a week into "Language", "languages"
-- and "English stuff", at which point browsing by field is no better than a flat list. The second
-- level (quizzes.subject) is free text, which is where the breadth actually lives.
--
-- Adding a field is a migration, deliberately. It should be a decision, not a side effect of
-- somebody typing into a form.
CREATE TABLE study_fields (
    id       SMALLINT    PRIMARY KEY,
    slug     VARCHAR(32) NOT NULL UNIQUE,
    name     VARCHAR(64) NOT NULL,
    -- Display order for the browse chips. Not alphabetical: the broad, well-populated fields sit
    -- first and "Other" is pinned last.
    position SMALLINT    NOT NULL
);

