-- Accounts, their sessions, and the events the throttles are built on.

CREATE TABLE users (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username      VARCHAR(64) NOT NULL,
    -- Required, because sharing a quiz with a friend notifies them by email. An account with no
    -- address would silently receive nothing, which is worse than not offering the feature.
    email         VARCHAR(254) NOT NULL,
    -- scrypt, in the form "scrypt$N$r$p$salt$hash". Never a plaintext password, and never seeded
    -- from a migration: the bootstrap admin is created at startup from ADMIN_USERNAME /
    -- ADMIN_PASSWORD, so no credential ever lands in version control.
    password_hash TEXT        NOT NULL,
    role          VARCHAR(16) NOT NULL DEFAULT 'USER',
    created_at    TIMESTAMP(6) WITH TIME ZONE NOT NULL DEFAULT NOW(),

    CONSTRAINT chk_users_role CHECK (role IN ('ADMIN', 'USER'))
);

-- Uniqueness on LOWER(username) rather than a plain UNIQUE, so "Allan" and "allan" cannot both
-- exist. Two accounts differing only in case are indistinguishable to a human reading a byline,
-- which is exactly the confusion an impersonator wants.
CREATE UNIQUE INDEX idx_users_username_lower ON users (LOWER(username));

-- Same reasoning, and the practical one: mail servers treat the local part's case as
-- insignificant in practice, so two accounts on one address would just be one person's inbox.
CREATE UNIQUE INDEX idx_users_email_lower ON users (LOWER(email));

-- A logged-in session.
--
-- id holds the SHA-256 of the token in the cookie, never the token itself. The distinction matters:
-- a leaked dump of this table then contains no credential anyone can present, because the hash
-- cannot be turned back into the cookie value. The session is opaque and revocable - deleting the
-- row logs that browser out immediately, which a self-contained signed token could not do.
CREATE TABLE sessions (
    id         TEXT   PRIMARY KEY,
    user_id    BIGINT NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    created_at TIMESTAMP(6) WITH TIME ZONE NOT NULL DEFAULT NOW(),
    expires_at TIMESTAMP(6) WITH TIME ZONE NOT NULL
);

CREATE INDEX idx_sessions_user ON sessions (user_id);
-- Supports sweeping expired rows without scanning the table.
CREATE INDEX idx_sessions_expires_at ON sessions (expires_at);

-- Backs both throttles: the per-IP signup cap and the login backoff.
--
-- Successful logins are deliberately not recorded here. This table exists to answer one question -
-- "has this address been misbehaving lately?" - and logging every successful sign-in would bloat
-- it without helping answer that. It is a courtesy throttle, not an audit log.
CREATE TABLE auth_events (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    -- VARCHAR(45) is the longest possible IPv6 text form, matching the messages table.
    ip         VARCHAR(45) NOT NULL,
    -- Nullable: a signup event has no prior username to attribute the attempt to.
    username   VARCHAR(64),
    kind       VARCHAR(16) NOT NULL,
    created_at TIMESTAMP(6) WITH TIME ZONE NOT NULL DEFAULT NOW(),

    CONSTRAINT chk_auth_events_kind CHECK (kind IN ('LOGIN_FAILURE', 'SIGNUP'))
);

-- The only query this table serves: "what has this IP done since <time>?". Descending on
-- created_at so the most recent events for an address are the first ones scanned.
CREATE INDEX idx_auth_events_ip_created_at ON auth_events (ip, created_at DESC);
