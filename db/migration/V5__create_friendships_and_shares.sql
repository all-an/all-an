-- Friends, and the two kinds of thing you can send them.

-- One row per pair of people, whichever of them asked first.
--
-- A request has to be accepted before anything can be sent, and that consent step is the whole
-- point: without it, anyone who learned a username could push quizzes - and emails - at a stranger.
CREATE TABLE friendships (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    requester_id BIGINT      NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    addressee_id BIGINT      NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    status       VARCHAR(16) NOT NULL DEFAULT 'PENDING',
    created_at   TIMESTAMP(6) WITH TIME ZONE NOT NULL DEFAULT NOW(),
    -- When the request was accepted. NULL while it is still pending.
    responded_at TIMESTAMP(6) WITH TIME ZONE,

    CONSTRAINT chk_friendships_status CHECK (status IN ('PENDING', 'ACCEPTED')),
    CONSTRAINT chk_friendships_not_self CHECK (requester_id <> addressee_id)
);

-- Friendship is symmetric but the row is not: it records who asked. Indexing the *unordered* pair
-- means A-requests-B and B-requests-A cannot both exist, so two people who happen to add each
-- other at the same time end up with one relationship rather than two mirror-image ones.
CREATE UNIQUE INDEX uq_friendships_pair
    ON friendships (LEAST(requester_id, addressee_id), GREATEST(requester_id, addressee_id));

-- Both directions are queried constantly ("my friends", "my pending requests"), and neither
-- column alone answers those, since either side may be the requester.
CREATE INDEX idx_friendships_requester ON friendships (requester_id, status);
CREATE INDEX idx_friendships_addressee ON friendships (addressee_id, status);

-- A quiz someone sent you. Grants read access and the right to take it, nothing more: the
-- recipient cannot edit it, and it does not become theirs.
CREATE TABLE quiz_shares (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    quiz_id        BIGINT NOT NULL REFERENCES quizzes (id) ON DELETE CASCADE,
    shared_by_id   BIGINT NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    shared_with_id BIGINT NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    created_at     TIMESTAMP(6) WITH TIME ZONE NOT NULL DEFAULT NOW(),
    -- Dismissing hides it from the recipient's list without revoking their access - they may well
    -- be part way through taking it.
    dismissed_at   TIMESTAMP(6) WITH TIME ZONE,

    -- Sharing the same quiz with the same person twice is one share, not two notifications.
    CONSTRAINT uq_quiz_shares UNIQUE (quiz_id, shared_with_id)
);

CREATE INDEX idx_quiz_shares_recipient ON quiz_shares (shared_with_id, created_at DESC);

-- A single question someone sent you, to copy into a quiz of your own.
--
-- Copying rather than granting access, because a question outside a quiz has nowhere to live: the
-- recipient's copy is an independent row they own and can edit, and the sender's original is
-- untouched. That also avoids two people editing one question through different quizzes.
CREATE TABLE question_shares (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    question_id    BIGINT NOT NULL REFERENCES questions (id) ON DELETE CASCADE,
    shared_by_id   BIGINT NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    shared_with_id BIGINT NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    created_at     TIMESTAMP(6) WITH TIME ZONE NOT NULL DEFAULT NOW(),
    -- Stamped the first time the recipient copies it. Kept rather than deleted so the list can
    -- show "already copied" instead of offering the same question again.
    copied_at      TIMESTAMP(6) WITH TIME ZONE,
    dismissed_at   TIMESTAMP(6) WITH TIME ZONE,

    CONSTRAINT uq_question_shares UNIQUE (question_id, shared_with_id)
);

CREATE INDEX idx_question_shares_recipient ON question_shares (shared_with_id, created_at DESC);
