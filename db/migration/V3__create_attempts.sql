-- One run through a quiz, and the answers given during it.

CREATE TABLE attempts (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id             BIGINT NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    -- SET NULL rather than CASCADE: deleting a quiz must not silently erase the history of people
    -- who took it. The snapshot below is what keeps the results page readable afterwards.
    quiz_id             BIGINT REFERENCES quizzes (id) ON DELETE SET NULL,
    quiz_title_snapshot VARCHAR(120) NOT NULL,

    started_at          TIMESTAMP(6) WITH TIME ZONE NOT NULL DEFAULT NOW(),
    -- NULL while the attempt is still in flight. Stamped when the last question is answered, or
    -- when the taker gives up and finishes early.
    finished_at         TIMESTAMP(6) WITH TIME ZONE
);

-- The history list: this user's attempts, newest first.
CREATE INDEX idx_attempts_user_started ON attempts (user_id, started_at DESC);

-- The questions this attempt drew, frozen at the moment it started.
--
-- Copying them rather than joining live to questions is the point: editing a quiz in one tab must
-- not change what is being asked in another, and a question deleted next week must not rewrite
-- what somebody answered last week. prompt_snapshot carries the wording; the answer columns carry
-- what happened.
CREATE TABLE attempt_questions (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    attempt_id      BIGINT   NOT NULL REFERENCES attempts (id) ON DELETE CASCADE,
    question_id     BIGINT   REFERENCES questions (id) ON DELETE SET NULL,
    prompt_snapshot TEXT     NOT NULL,
    position        SMALLINT NOT NULL,

    -- When the server handed this question out. The countdown is measured from here, not from any
    -- clock the client controls, so pausing or tampering with the browser buys nothing. NULL until
    -- the question is actually served.
    served_at       TIMESTAMP(6) WITH TIME ZONE,
    answered_at     TIMESTAMP(6) WITH TIME ZONE,

    -- Exactly one of these is set, according to the question's kind.
    given_text      TEXT,
    given_option_id BIGINT REFERENCES question_options (id) ON DELETE SET NULL,

    -- NULL until answered. FALSE with timed_out = TRUE is a question that ran out of time.
    is_correct      BOOLEAN,
    timed_out       BOOLEAN  NOT NULL DEFAULT FALSE,
    elapsed_ms      INTEGER,

    CONSTRAINT uq_attempt_questions_attempt_position UNIQUE (attempt_id, position)
);
