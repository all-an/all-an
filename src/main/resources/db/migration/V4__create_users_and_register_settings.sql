-- Auth: an admin-controlled registration switch.
--
-- register_settings is a deliberately single-row table (enforced by the id CHECK). The flag lives
-- in the database, not in application.yml, because the admin toggles it at runtime and it must
-- survive restarts and redeploys.
--
-- IMPORTANT: hiding the register button in Angular is UX, not security. AuthController must read
-- this flag and reject POST /api/auth/register with 403 when it is false. Anyone can curl the
-- endpoint with the button hidden.
CREATE TABLE register_settings (
    id                   SMALLINT PRIMARY KEY DEFAULT 1,
    registration_enabled BOOLEAN NOT NULL DEFAULT TRUE,
    updated_at           TIMESTAMP(6) WITH TIME ZONE NOT NULL DEFAULT NOW(),
    updated_by           VARCHAR(64),

    CONSTRAINT chk_register_settings_single_row CHECK (id = 1)
);

INSERT INTO register_settings (id, registration_enabled) VALUES (1, TRUE);

CREATE TABLE users (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username      VARCHAR(64)  NOT NULL UNIQUE,
    -- BCrypt hash. Never a plaintext password, and never seeded from a migration:
    -- the bootstrap admin is created at startup from ADMIN_USERNAME / ADMIN_PASSWORD.
    password_hash VARCHAR(72)  NOT NULL,
    role          VARCHAR(16)  NOT NULL DEFAULT 'USER',
    enabled       BOOLEAN      NOT NULL DEFAULT TRUE,
    created_at    TIMESTAMP(6) WITH TIME ZONE NOT NULL DEFAULT NOW(),

    CONSTRAINT chk_users_role CHECK (role IN ('ADMIN', 'USER'))
);

CREATE INDEX idx_users_username ON users (username);
