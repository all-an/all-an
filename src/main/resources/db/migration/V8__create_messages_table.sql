-- Contact form submissions, rate limited to one per IP per calendar day.
--
-- ip is VARCHAR(45) because that is the longest possible IPv6 text form
-- ("ffff:ffff:ffff:ffff:ffff:ffff:255.255.255.255"). It stores the client address resolved from
-- X-Forwarded-For, so it is only as trustworthy as the proxy in front of the app - fine as a
-- courtesy throttle, not as a security control.
--
-- name and email are nullable: the form asks for a message and nothing else is required. Without
-- an email there is simply no way to reply, which is the sender's choice to make.
CREATE TABLE messages (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ip         VARCHAR(45)  NOT NULL,
    name       VARCHAR(80),
    email      VARCHAR(254),
    body       TEXT         NOT NULL,
    created_at TIMESTAMP(6) WITH TIME ZONE NOT NULL
);

-- The only query this table serves on the write path: "has this IP posted since midnight?".
-- Descending on created_at so the newest row for an IP is the first one scanned.
CREATE INDEX idx_messages_ip_created_at ON messages (ip, created_at DESC);
