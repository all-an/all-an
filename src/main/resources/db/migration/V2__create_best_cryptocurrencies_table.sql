-- Privacy-first ranking of cryptocurrencies.
--
-- Column order is deliberate: privacy and privacy_kind lead, because the ranking is an
-- editorial judgement about privacy rather than market cap. See CRYPTO-ROADMAP.md.
CREATE TABLE best_cryptocurrencies (
    id                       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    -- the thesis columns
    privacy                  VARCHAR(16) NOT NULL,   -- MANDATORY | OPTIONAL | NONE
    privacy_kind             VARCHAR(32) NOT NULL,   -- RING_SIGNATURES_RINGCT | ZK_SNARKS | ...
    privacy_by_default       BOOLEAN     NOT NULL,   -- the Monero vs Zcash differentiator
    anonymity_set            VARCHAR(64) NOT NULL,
    trusted_setup_required   BOOLEAN     NOT NULL,
    fungibility              VARCHAR(16) NOT NULL,   -- STRONG | PARTIAL | NONE

    -- identity
    rank                     INTEGER     NOT NULL UNIQUE,
    name                     VARCHAR(64) NOT NULL,
    symbol                   VARCHAR(16) NOT NULL UNIQUE,

    -- mechanics (approximate snapshot - see CRYPTO-ROADMAP.md "Data honesty")
    transaction_time_seconds INTEGER     NOT NULL,
    transaction_fee_usd      NUMERIC(12, 4) NOT NULL,
    block_time_seconds       INTEGER     NOT NULL,
    consensus                VARCHAR(48) NOT NULL,
    launch_year              INTEGER     NOT NULL,
    supply_cap               NUMERIC(24, 0),         -- null = uncapped
    smart_contracts          BOOLEAN     NOT NULL,

    -- maintained by hand
    price_usd                NUMERIC(18, 6),         -- null = not filled in yet
    price_date               DATE,                   -- the day the price refers to (you set this)
    price_updated_at         TIMESTAMP(6) WITH TIME ZONE, -- when the row was written (server-stamped)

    notes                    TEXT,

    CONSTRAINT chk_privacy CHECK (privacy IN ('MANDATORY', 'OPTIONAL', 'NONE')),
    CONSTRAINT chk_fungibility CHECK (fungibility IN ('STRONG', 'PARTIAL', 'NONE'))
);

CREATE INDEX idx_best_cryptocurrencies_rank ON best_cryptocurrencies (rank);
CREATE INDEX idx_best_cryptocurrencies_privacy ON best_cryptocurrencies (privacy);
